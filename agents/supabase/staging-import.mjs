// node staging-import.mjs build <dump.sql>   writes migrations/<version>_baseline_from_staging.sql
// node --env-file=<repo>/.env staging-import.mjs load <dump.sql>   applies that migration, then loads the data
//
// Data rules (agreed 2026-10-11): every email outside facundo.* keeps its address but its TLD becomes
// ".example" (reserved, undeliverable); every auth password becomes SUPABASE_MOCK_USER_PASSWORD; live
// credentials (sessions, refresh tokens, magic-login tokens, push subscriptions, vault) are not copied.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const VERSION = '20261011130000';
const MIGRATION = path.join(HERE, 'migrations', `${VERSION}_baseline_from_staging.sql`);
const APP_SCHEMAS = new Set(['public', 'stats_sandbox']);
const SKIP_DATA = new Set(['public.florist_magic_tokens', 'public.push_subscriptions']);
const AUTH_DATA = ['auth.users', 'auth.identities'];

const HEADER = /^-- (Data for )?Name: (.*); Type: (.*); Schema: (.*); Owner: .*$/;

function parse(file) {
  const entries = [];
  let cur = null;
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const h = HEADER.exec(line);
    if (h) { cur = { name: h[2], type: h[3], schema: h[4], lines: [] }; entries.push(cur); continue; }
    if (cur) cur.lines.push(line);
  }
  return entries;
}

const isSchemaEntry = (e) =>
  (APP_SCHEMAS.has(e.schema) && e.type !== 'TABLE DATA' && e.type !== 'SEQUENCE SET') ||
  (e.schema === '-' && e.type === 'SCHEMA' && e.name === 'stats_sandbox') ||
  (e.schema === '-' && e.type === 'EXTENSION' && e.name === 'pg_trgm') ||
  (e.schema === '-' && e.type === 'ACL' && e.name === 'SCHEMA stats_sandbox');

const keepLine = (l) => !/^ALTER .* OWNER TO /.test(l) && !l.includes('supabase_admin') && !l.startsWith('\\restrict') && !l.startsWith('\\unrestrict');

function buildMigration(entries) {
  const body = entries.filter(isSchemaEntry)
    .map((e) => e.lines.filter(keepLine).join('\n').replace(/^CREATE SCHEMA /m, 'CREATE SCHEMA IF NOT EXISTS ').trim())
    .filter(Boolean).join('\n\n');
  // Needs stats_reader's CREATE on stats_sandbox, which the dump grants after the function.
  const owners = entries.filter(isSchemaEntry).flatMap((e) => e.lines.filter((l) => /^ALTER .* OWNER TO stats_reader;/.test(l)));
  return `-- Baseline: the public + stats_sandbox schema of Facundo staging, from pg_dump 2026-10-11 11:14.
-- Generated by agents/supabase/staging-import.mjs build. Supabase-managed schemas are left to the platform.
SET check_function_bodies = false;

-- pg_dump does not export roles. As in supabase/migrations/2026-08-05-stats-reader-role.sql:
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'stats_reader') THEN CREATE ROLE stats_reader NOLOGIN BYPASSRLS; END IF;
END $$;
GRANT stats_reader TO postgres WITH INHERIT TRUE, SET TRUE;

${body}

${owners.join('\n')}
`;
}

const EMAIL = /([A-Za-z0-9._%+-]+)@((?:[A-Za-z0-9-]+\.)+)([A-Za-z]{2,24})(?![A-Za-z0-9-])/g;
const stats = { rewritten: 0, kept: 0 };
function maskEmails(line) {
  return line.replace(EMAIL, (m, local, domain, tld) => {
    if (/(^|\.)facundo\.$/i.test(domain) || tld.toLowerCase() === 'example') { stats.kept++; return m; }
    stats.rewritten++;
    return `${local}@${domain}example`;
  });
}

function dataBlocks(entries) {
  const blocks = [];
  for (const e of entries) {
    if (e.type !== 'TABLE DATA') continue;
    const table = `${e.schema}.${e.name}`;
    if (!(APP_SCHEMAS.has(e.schema) && !SKIP_DATA.has(table)) && !AUTH_DATA.includes(table)) continue;
    const start = e.lines.findIndex((l) => l.startsWith('COPY '));
    const end = e.lines.indexOf('\\.', start);
    blocks.push({ table, copy: e.lines[start], rows: e.lines.slice(start + 1, end).map(maskEmails) });
  }
  const auth = blocks.filter((b) => b.table.startsWith('auth.'));
  return [...AUTH_DATA.map((t) => auth.find((b) => b.table === t)).filter(Boolean), ...blocks.filter((b) => !b.table.startsWith('auth.'))];
}

function client() {
  const ref = new URL(process.env.SUPABASE_CONNECTION_STRING.replace('[YOUR-PASSWORD]', 'x')).hostname.split('.')[1];
  return new pg.Client({
    host: process.env.SUPABASE_POOLER_HOST ?? 'aws-0-your-region.pooler.supabase.com', port: 6543,
    user: `postgres.${ref}`, password: process.env.SUPABASE_DATABASE_PASSWORD, database: 'postgres', ssl: { rejectUnauthorized: false },
    query_timeout: 120_000,
  });
}

async function connect() {
  const c = client();
  c.on('error', () => {});
  await c.connect();
  return c;
}

// Large messages stall or get cut on some networks: keep batches small, and on a dropped connection
// reconnect and resume (every batch is its own transaction, so a retry never duplicates rows).
const BATCH_BYTES = 256 * 1024;
const MAX_PARAMS = 60000;

const ESC = { b: '\b', f: '\f', n: '\n', r: '\r', t: '\t', v: '\v', '\\': '\\' };
function decodeField(f) {
  if (f === '\\N') return null;
  return f.replace(/\\(x[0-9a-fA-F]{1,2}|[0-7]{1,3}|.)/g, (_, e) =>
    e[0] === 'x' ? String.fromCharCode(parseInt(e.slice(1), 16))
      : /^[0-7]/.test(e) ? String.fromCharCode(parseInt(e, 8))
      : ESC[e] ?? e);
}

// COPY ... FROM STDIN through Supabase's transaction pooler hangs here (2026-10-11), so rows go in as
// untyped parameters, which Postgres parses with each column's own input function, exactly as COPY would.
async function insertBatch(c, copy, rows) {
  const [, table, cols] = /^COPY (\S+) \((.*)\) FROM stdin;$/.exec(copy);
  const n = cols.split(', ').length;
  const params = rows.flatMap((r) => r.split('\t').map(decodeField));
  const tuples = rows.map((_, i) => `(${Array.from({ length: n }, (_, j) => `$${i * n + j + 1}`).join(',')})`);
  await c.query('begin');
  await c.query('set local session_replication_role = replica; set local statement_timeout = 0');
  await c.query(`insert into ${table} (${cols}) values ${tuples.join(',')}`, params);
  await c.query('commit');
}

// Rows go in dump order, one committed batch at a time, so the row count already present is where to resume.
async function loadBlock(c, block) {
  const have = (await c.query(`select count(*)::int n from ${block.table}`)).rows[0].n;
  if (have > block.rows.length) throw new Error(`${block.table} has ${have} rows, more than the dump's ${block.rows.length}`);
  const perBatch = Math.floor(MAX_PARAMS / block.copy.split(', ').length);
  let batch = [], bytes = 0;
  for (const row of block.rows.slice(have)) {
    batch.push(row); bytes += row.length;
    if (bytes >= BATCH_BYTES || batch.length >= perBatch) { await insertBatch(c, block.copy, batch); batch = []; bytes = 0; }
  }
  if (batch.length) await insertBatch(c, block.copy, batch);
  return have;
}

async function load(entries) {
  const mock = process.env.SUPABASE_MOCK_USER_PASSWORD;
  if (!mock) throw new Error('SUPABASE_MOCK_USER_PASSWORD is not set');
  let c = await connect();
  await c.query('create schema if not exists supabase_migrations; create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text)');
  const applied = (await c.query('select 1 from supabase_migrations.schema_migrations where version = $1', [VERSION])).rowCount > 0;
  if (!applied) {
    await c.query('begin');
    await c.query(fs.readFileSync(MIGRATION, 'utf8'));
    await c.query(`insert into supabase_migrations.schema_migrations (version, name) values ($1, 'baseline_from_staging')`, [VERSION]);
    await c.query('commit');
    console.log('applied migration', path.basename(MIGRATION));
  }
  const blocks = dataBlocks(entries);
  for (const b of blocks) {
    const t0 = Date.now();
    for (let attempt = 1; ; attempt++) {
      try {
        const had = await loadBlock(c, b);
        console.log(`loaded ${b.table} (${b.rows.length - had} new rows, ${((Date.now() - t0) / 1000).toFixed(0)}s)`);
        break;
      } catch (e) {
        if (attempt >= 5 || e.code) throw e;
        console.log(`${b.table}: ${e.message}; reconnecting (attempt ${attempt + 1})`);
        c.end().catch(() => {});
        c = await connect();
      }
    }
  }
  for (const e of entries.filter((x) => x.type === 'SEQUENCE SET' && APP_SCHEMAS.has(x.schema))) await c.query(e.lines.filter((l) => l.startsWith('SELECT')).join('\n'));
  await c.query(`update auth.users set encrypted_password = extensions.crypt($1, extensions.gen_salt('bf')) where coalesce(encrypted_password, '') <> ''`, [mock]);
  await c.query(`update auth.users set confirmation_token = '', recovery_token = '', email_change_token_new = '', email_change_token_current = '', reauthentication_token = '', phone_change_token = ''`);
  for (const b of blocks) {
    const n = (await c.query(`select count(*)::int n from ${b.table}`)).rows[0].n;
    console.log(`${n === b.rows.length ? 'OK ' : 'BAD'} ${b.table} ${n}/${b.rows.length}`);
  }
  console.log(`emails rewritten ${stats.rewritten}, kept (facundo) ${stats.kept}; skipped data: ${[...SKIP_DATA].join(', ')}`);
  await c.end();
}

const [mode, dump] = process.argv.slice(2);
const entries = parse(dump);
if (mode === 'build') {
  fs.mkdirSync(path.dirname(MIGRATION), { recursive: true });
  fs.writeFileSync(MIGRATION, buildMigration(entries));
  const kinds = {};
  for (const e of entries.filter(isSchemaEntry)) kinds[e.type] = (kinds[e.type] ?? 0) + 1;
  console.log('wrote', MIGRATION, kinds);
} else if (mode === 'load') {
  await load(entries);
} else {
  console.error('usage: staging-import.mjs build|load <dump.sql>');
  process.exit(1);
}
